
import os
import sqlite3
from pathlib import Path

DB_PATH = Path(__file__).resolve().parent / "repevolution.db"
DATABASE_URL = os.environ.get("DATABASE_URL")




class PostgresCursorAdapter:
    def __init__(self, cursor, is_insert=False):
        self._cursor = cursor
        self._is_insert = is_insert

    @property
    def lastrowid(self):
        if not self._is_insert:
            return None

        row = self._cursor.fetchone()
        return row["id"] if row else None

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class PostgresConnectionAdapter:
    def __init__(self, connection):
        self._connection = connection

    def __enter__(self):
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self._connection.__exit__(
            exc_type, exc_value, traceback
        )

    def execute(self, sql, params=None):
        import re
        import sqlite3
        import psycopg

        sql = sql.replace("?", "%s")

        is_insert = bool(
            re.match(r"^\s*INSERT\b", sql, re.IGNORECASE)
        )

        if is_insert and not re.search(
            r"\bRETURNING\b", sql, re.IGNORECASE
        ):
            sql = sql.rstrip().rstrip(";") + " RETURNING id"

        try:
            cursor = self._connection.execute(
                sql,
                params if params is not None else ()
            )
        except psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError(str(error)) from error

        return PostgresCursorAdapter(cursor, is_insert)





def conectar():
    """Usa Neon si DATABASE_URL existe; de lo contrario, SQLite."""
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        conexion = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=10
        )

        return PostgresConnectionAdapter(conexion)

    conexion = sqlite3.connect(DB_PATH)
    conexion.row_factory = sqlite3.Row
    conexion.execute("PRAGMA foreign_keys = ON")
    return conexion


def inicializar_db():
    if DATABASE_URL:
        inicializar_postgres()
    else:
        inicializar_sqlite()


